export type IconName = keyof typeof icons;
export default function Icon({
  name,
  size = 18,
  ...props
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const I = icons[name as IconName] || BookOpen;
  return <I size={size} strokeWidth={1.65} aria-hidden="true" {...props} />;
}
